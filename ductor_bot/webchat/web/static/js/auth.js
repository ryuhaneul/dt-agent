import { api, ApiError, setCsrf } from './api.js';
import { t } from './i18n.js';
import { go, setAuthenticated, setPreauth } from './router.js';
let busy = false;
let setupMode = 'new';
let preparedSeed = null;
let setupReady = false;

export function notify(key, values = {}) {
  const toast = document.createElement('div');
  toast.className = 'toast toast-error';
  toast.setAttribute('role', 'alert');
  const message = document.createElement('span');
  message.textContent = t(key, values);
  const close = document.createElement('button');
  close.type = 'button'; close.className = 'toast-close';
  close.setAttribute('aria-label', t('common.close'));
  close.textContent = '×';
  close.addEventListener('click', () => toast.remove());
  toast.append(message, close);
  document.querySelector('#toasts').appendChild(toast);
  setTimeout(() => toast.remove(), 5000);
}

function showError(error) {
  if (error instanceof ApiError && error.code === 'auth_required') return;
  const key = error instanceof ApiError && error.code === 'locked' ? 'auth.locked'
    : error instanceof ApiError && error.code === 'code_reused' ? 'auth.code_reused'
    : error instanceof ApiError && error.code === 'bot_unreachable' ? 'error.bot_unreachable'
    : error instanceof ApiError && ['invalid', 'bad_secret'].includes(error.code) ? 'auth.invalid'
    : 'error.generic';
  notify(key, { minutes: Math.max(1, Math.ceil((error.retryAfter || 0) / 60)) });
}

async function perform(action) {
  if (busy) return;
  busy = true;
  const buttons = [...document.querySelectorAll('#auth button')]
    .filter(button => button.dataset.setupMode === undefined);
  buttons.forEach(button => { button.disabled = true; });
  document.querySelector('#auth').setAttribute('aria-busy', 'true');
  try { await action(); }
  catch (error) { showError(error); }
  finally {
    busy = false;
    buttons.forEach(button => { button.disabled = false; });
    document.querySelector('#auth').removeAttribute('aria-busy');
  }
}

function clearCodes() {
  document.querySelectorAll('.otp input').forEach(input => { input.value = ''; });
}
function clearSetup() {
  preparedSeed = null; setupReady = false;
  document.querySelector('.seed').textContent = '';
  document.querySelector('#seedIn').value = '';
  document.querySelector('#qr').replaceChildren();
}

export function mountOtp(element, submit) {
  element.replaceChildren();
  for (let index = 0; index < 6; index++) {
    const input = document.createElement('input');
    input.className = 'field'; input.type = 'text'; input.inputMode = 'numeric';
    input.maxLength = 1; input.pattern = '[0-9]'; input.required = true;
    input.autocomplete = index === 0 ? 'one-time-code' : 'off';
    input.setAttribute('aria-label', t('auth.digit', { n: index + 1 }));
    input.addEventListener('input', () => {
      input.value = input.value.replace(/[^0-9]/g, '').slice(-1);
      if (input.value) input.nextElementSibling?.focus();
      if (code(element).length === 6) submit();
    });
    input.addEventListener('keydown', event => {
      if (event.key === 'Backspace' && !input.value) input.previousElementSibling?.focus();
      if (event.key === 'ArrowLeft') input.previousElementSibling?.focus();
      if (event.key === 'ArrowRight') input.nextElementSibling?.focus();
    });
    input.addEventListener('paste', event => {
      event.preventDefault();
      const digits = event.clipboardData.getData('text').replace(/[^0-9]/g, '').slice(0, 6);
      const inputs = [...element.querySelectorAll('input')];
      inputs.forEach((box, number) => { box.value = digits[number] || ''; });
      inputs[Math.min(digits.length, 5)].focus();
      if (digits.length === 6) submit();
    });
    element.appendChild(input);
  }
}
function code(element) { return [...element.querySelectorAll('input')].map(input => input.value).join(''); }

async function refreshState() {
  const state = await api('/auth/state');
  setCsrf(state.csrf);
  setAuthenticated(state.authenticated);
  document.querySelector('#setupLink').hidden = state.totp_configured !== false;
  const badge = document.querySelector('#botBadge');
  badge.className = `badge ${state.bridge_up ? 'badge-ok' : 'badge-down'}`;
  const label = badge.querySelector('span');
  label.dataset.i18n = state.bridge_up ? 'status.bot_up' : 'status.bot_down';
  label.textContent = t(label.dataset.i18n);
  return state;
}

async function beginSetup(mode) {
  const body = mode === 'new' ? { mode } : { mode, secret: document.querySelector('#seedIn').value };
  const result = await api('/auth/setup/begin', { method: 'POST', body });
  document.querySelector('.seed').textContent = result.secret_display;
  const qr = document.querySelector('#qr');
  qr.replaceChildren();
  if (mode === 'new') {
    // QR markup is generated by our server. Import only an SVG, never an HTML document.
    const svg = new DOMParser().parseFromString(result.qr_svg, 'image/svg+xml').documentElement;
    if (svg.localName !== 'svg' || svg.namespaceURI !== 'http://www.w3.org/2000/svg') throw new Error('bad_qr');
    qr.appendChild(document.importNode(svg, true));
  }
  preparedSeed = mode === 'paste' ? document.querySelector('#seedIn').value : null;
  setupReady = true;
}

function selectSetupMode(mode) {
  setupMode = mode;
  preparedSeed = null; setupReady = false;
  document.querySelectorAll('[data-setup-mode]').forEach(button =>
    button.setAttribute('aria-selected', String(button.dataset.setupMode === mode)));
  document.querySelector('#setupNew').classList.toggle('hidden', mode !== 'new');
  document.querySelector('#setupPaste').classList.toggle('hidden', mode !== 'paste');
  document.querySelector('#qr').replaceChildren();
  document.querySelector('.seed').textContent = '';
  document.querySelector('#otp2').querySelectorAll('input').forEach(input => { input.value = ''; });
}

function submitTotp() {
  const value = code(document.querySelector('#otp'));
  if (!/^[0-9]{6}$/.test(value)) return;
  return perform(async () => {
    await api('/auth/totp', { method: 'POST', body: { code: value } });
    clearCodes(); clearSetup(); setPreauth(false);
    await refreshState();
    go('chat');
  });
}
function confirmSetup() {
  const value = code(document.querySelector('#otp2'));
  if (!/^[0-9]{6}$/.test(value)) return;
  return perform(async () => {
    if (setupMode === 'paste' && preparedSeed !== document.querySelector('#seedIn').value) await beginSetup('paste');
    if (!setupReady) return;
    await api('/auth/setup/confirm', { method: 'POST', body: { code: value } });
    clearCodes(); clearSetup(); setPreauth(false);
    await refreshState();
    go('pw');
  });
}

export async function initAuth() {
  mountOtp(document.querySelector('#otp'), submitTotp);
  mountOtp(document.querySelector('#otp2'), confirmSetup);
  document.querySelector('#pwForm').addEventListener('submit', event => {
    event.preventDefault();
    perform(async () => {
      const password = document.querySelector('#pw');
      const body = { password: password.value };
      password.value = '';
      const result = await api('/auth/password', { method: 'POST', body });
      setPreauth(true); clearCodes(); clearSetup();
      if (result.next === 'setup') { selectSetupMode('new'); go('setup'); await beginSetup('new'); }
      else go('totp');
    });
  });
  document.querySelector('#totpForm').addEventListener('submit', event => { event.preventDefault(); submitTotp(); });
  document.querySelector('#setupForm').addEventListener('submit', event => { event.preventDefault(); confirmSetup(); });
  document.querySelector('#setupLink').addEventListener('click', event => {
    event.preventDefault(); notify('auth.setup_needs_password'); go('pw'); document.querySelector('#pw').focus();
  });
  document.querySelector('#regenerate').addEventListener('click', async () => {
    await perform(() => beginSetup('new'));
    if (!busy) document.querySelector('#regenerate').focus();
  });
  document.querySelectorAll('[data-setup-mode]').forEach(button => {
    button.addEventListener('click', () => {
      if (busy || button.dataset.setupMode === setupMode) return;
      selectSetupMode(button.dataset.setupMode);
      if (setupMode === 'new') perform(() => beginSetup('new'));
    });
    button.addEventListener('keydown', event => {
      if (!['ArrowLeft', 'ArrowRight'].includes(event.key)) return;
      event.preventDefault();
      const other = document.querySelector(`[data-setup-mode="${setupMode === 'new' ? 'paste' : 'new'}"]`);
      other.click(); other.focus();
    });
  });
  document.addEventListener('route-change', event => {
    if (event.detail.route === 'pw') { setPreauth(false); clearCodes(); clearSetup(); }
  });
  document.addEventListener('auth-required', () => {
    setAuthenticated(false); setPreauth(false); clearCodes(); clearSetup(); go('pw');
  });
  const state = await refreshState();
  go(state.authenticated ? 'chat' : 'pw');
}
